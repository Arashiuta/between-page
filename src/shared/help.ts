export function searchHelp(query: string): HelpCategory[] {
  const term = query.trim().toLocaleLowerCase();
  return helpCategories
    .map((c) => ({
      ...c,
      articles: c.articles.filter(
        (a) =>
          !term ||
          [
            c.title,
            a.title,
            a.body,
            a.note,
            ...(a.steps ?? []),
            ...(a.links?.map((l) => l.label) ?? []),
          ]
            .join(" ")
            .toLocaleLowerCase()
            .includes(term),
      ),
    }))
    .filter((c) => c.articles.length);
}
