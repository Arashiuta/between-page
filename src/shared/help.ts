export function searchHelp(query: string): HelpCategory[] {
  const term = query.trim().toLocaleLowerCase();
  return helpCategories
    .map((category) => ({
      ...category,
      articles: category.articles.filter(
        (article) =>
          !term ||
          [
            category.title,
            article.title,
            article.body,
            article.note,
            ...(article.steps ?? []),
            ...(article.links?.map((link) => link.label) ?? []),
          ]
            .join(" ")
            .toLocaleLowerCase()
            .includes(term),
      ),
    }))
    .filter((category) => category.articles.length);
}
